def load_payload() -> torch.Tensor:
    """
    Load the ORIGINAL watermark payload.

    This is deliberately loaded from:

        results/watermark/payload_bits.pt

    rather than from the QIM embedding output.

    Reason:
        The original payload is the independent ground truth
        against which extraction must be evaluated.
    """

    check_file_exists(
        PAYLOAD_FILE,
        "Original payload file",
    )

    payload = torch.load(
        PAYLOAD_FILE,
        map_location="cpu",
        weights_only=False,
    )

    if not isinstance(payload, torch.Tensor):
        payload = torch.tensor(payload)

    payload = payload.flatten().to(
        torch.int64
    )

    # --------------------------------------------------------
    # Validate binary payload
    # --------------------------------------------------------

    unique_values = torch.unique(
        payload
    ).tolist()

    invalid_values = [
        value
        for value in unique_values
        if value not in (0, 1)
    ]

    if invalid_values:
        raise ValueError(
            "\nPayload contains values other than "
            "binary 0/1:\n"
            f"{invalid_values}"
        )

    # --------------------------------------------------------
    # Validate expected length
    # --------------------------------------------------------

    if payload.numel() != PAYLOAD_LENGTH:
        raise ValueError(
            "\nUnexpected payload length.\n"
            f"Expected : {PAYLOAD_LENGTH}\n"
            f"Found    : {payload.numel()}"
        )

    return payload


# ============================================================
# COORDINATE LOADING
# ============================================================

def load_coordinates() -> pd.DataFrame:
    """
    Load the exact coefficient coordinates selected by
    Experiment 17.
    """

    check_file_exists(
        COORDINATES_FILE,
        "QIM coordinate file",
    )

    coordinates = pd.read_csv(
        COORDINATES_FILE
    )

    required_columns = [
        "bit_index",
        "payload_bit",
        "region_id",
        "time_frame",
        "frequency_bin",
        "semantic_score",
        "adaptive_delta",
        "original_real",
        "watermarked_real",
        "delta_change",
    ]

    missing_columns = [
        column
        for column in required_columns
        if column not in coordinates.columns
    ]

    if missing_columns:
        raise ValueError(
            "\nMissing required columns in QIM coordinate file:\n"
            f"{missing_columns}\n\n"
            "Available columns:\n"
            f"{list(coordinates.columns)}"
        )

    # --------------------------------------------------------
    # Sort according to payload bit index.
    # --------------------------------------------------------

    coordinates = coordinates.sort_values(
        "bit_index"
    ).reset_index(drop=True)

    # --------------------------------------------------------
    # Validate coordinate count.
    # --------------------------------------------------------

    if len(coordinates) != PAYLOAD_LENGTH:
        raise ValueError(
            "\nUnexpected number of coordinate rows.\n"
            f"Expected : {PAYLOAD_LENGTH}\n"
            f"Found    : {len(coordinates)}"
        )

    # --------------------------------------------------------
    # Validate bit indices.
    # --------------------------------------------------------

    expected_indices = list(
        range(PAYLOAD_LENGTH)
    )

    actual_indices = (
        coordinates["bit_index"]
        .astype(int)
        .tolist()
    )

    if actual_indices != expected_indices:
        raise ValueError(
            "\nQIM coordinate bit_index values are not "
            "a complete ordered sequence from 0 to 255."
        )

    # --------------------------------------------------------
    # Validate binary payload bits.
    # --------------------------------------------------------

    coordinate_bits = (
        coordinates["payload_bit"]
        .astype(int)
        .to_numpy()
    )

    invalid_bits = np.unique(
        coordinate_bits[
            ~np.isin(
                coordinate_bits,
                [0, 1],
            )
        ]
    )

    if len(invalid_bits) > 0:
        raise ValueError(
            "\nCoordinate file contains invalid payload bits:\n"
            f"{invalid_bits.tolist()}"
        )

    # --------------------------------------------------------
    # Validate adaptive QIM deltas.
    # --------------------------------------------------------

    deltas = (
        coordinates["adaptive_delta"]
        .astype(float)
        .to_numpy()
    )

    if np.any(~np.isfinite(deltas)):
        raise ValueError(
            "\nCoordinate file contains non-finite "
            "adaptive_delta values."
        )

    if np.any(deltas <= 0):
        raise ValueError(
            "\nCoordinate file contains non-positive "
            "adaptive_delta values."
        )

    return coordinates


# ============================================================
# PAYLOAD / COORDINATE CONSISTENCY
# ============================================================

def validate_payload_against_coordinates(
    payload: torch.Tensor,
    coordinates: pd.DataFrame,
) -> None:
    """
    Verify that the payload bits used by Experiment 17
    correspond exactly to the original payload.

    This is a critical experimental integrity check.

    We do NOT use coordinate payload bits as the primary
    ground truth. Instead, we compare them against the
    original payload.
    """

    payload_array = (
        payload
        .cpu()
        .numpy()
        .astype(int)
    )

    coordinate_bits = (
        coordinates["payload_bit"]
        .astype(int)
        .to_numpy()
    )

    matching_bits = int(
        np.sum(
            payload_array
            == coordinate_bits
        )
    )

    mismatching_bits = (
        PAYLOAD_LENGTH
        - matching_bits
    )

    print()
    print(
        "Payload / Coordinate Validation"
    )
    print(
        "--------------------------------"
    )

    print(
        f"Original Payload Bits : "
        f"{PAYLOAD_LENGTH}"
    )

    print(
        f"Coordinate Payload Bits: "
        f"{len(coordinate_bits)}"
    )

    print(
        f"Matching Bits         : "
        f"{matching_bits}"
    )

    print(
        f"Mismatching Bits      : "
        f"{mismatching_bits}"
    )

    if mismatching_bits != 0:

        raise ValueError(
            "\nThe payload recorded in the QIM coordinate "
            "file does not match the original payload.\n\n"
            "This means Experiment 17 may have embedded a "
            "different payload than the expected watermark."
        )

    print(
        "Payload Consistency   : PASSED"
    )


# ============================================================
# STFT LOADING
# ============================================================

def load_watermarked_stft() -> torch.Tensor:
    """
    Load the complex watermarked STFT produced by Exp17.
    """

    check_file_exists(
        WATERMARKED_STFT_FILE,
        "QIM watermarked STFT",
    )

    stft = torch.load(
        WATERMARKED_STFT_FILE,
        map_location="cpu",
        weights_only=False,
    )

    if not isinstance(stft, torch.Tensor):
        stft = torch.tensor(stft)

    if stft.ndim != 2:
        raise ValueError(
            "\nWatermarked STFT must be a 2D tensor.\n"
            f"Shape: {tuple(stft.shape)}"
        )

    expected_shape = (
        513,
        522,
    )

    if tuple(stft.shape) != expected_shape:

        raise ValueError(
            "\nUnexpected STFT shape.\n"
            f"Expected : {expected_shape}\n"
            f"Found    : {tuple(stft.shape)}"
        )

    if not torch.is_complex(stft):

        raise ValueError(
            "\nWatermarked STFT is not complex.\n"
            "QIM extraction expects the complex STFT "
            "generated by Experiment 17."
        )

    return stft


# ============================================================
# QIM DECODER
# ============================================================

def decode_qim(
    coefficient: complex,
    delta: float,
) -> int:
    """
    Decode a binary QIM symbol.

    Experiment 17 modifies the real component of the STFT.

    Binary QIM decision rule:

        bit_hat =
            round(real(y) / Delta) mod 2

    where:

        y     = received/watermarked coefficient
        Delta = adaptive QIM step size
    """

    if not np.isfinite(delta):
        raise ValueError(
            "QIM delta is not finite."
        )

    if delta <= 0:
        raise ValueError(
            f"QIM delta must be > 0, got {delta}"
        )

    real_value = float(
        np.real(coefficient)
    )

    quantization_index = int(
        np.rint(
            real_value / delta
        )
    )

    decoded_bit = (
        quantization_index % 2
    )

    return int(decoded_bit)


# ============================================================
# QIM EXTRACTION FROM STFT
# ============================================================

def extract_bits_from_stft(
    stft: torch.Tensor,
    coordinates: pd.DataFrame,
) -> tuple[list[int], list[dict]]:
    """
    Extract all 256 bits from a supplied STFT.

    The exact coordinates and adaptive deltas recorded
    during Experiment 17 are reused.
    """

    extracted_bits: list[int] = []

    details: list[dict] = []

    for _, row in coordinates.iterrows():

        bit_index = int(
            row["bit_index"]
        )

        expected_bit = int(
            row["payload_bit"]
        )

        region_id = int(
            row["region_id"]
        )

        time_frame = int(
            row["time_frame"]
        )

        frequency_bin = int(
            row["frequency_bin"]
        )

        semantic_score = float(
            row["semantic_score"]
        )

        adaptive_delta = float(
            row["adaptive_delta"]
        )

        # ----------------------------------------------------
        # Bounds check
        # ----------------------------------------------------

        if (
            frequency_bin < 0
            or frequency_bin >= stft.shape[0]
        ):

            raise IndexError(
                "\nFrequency bin outside STFT bounds.\n"
                f"Bit index     : {bit_index}\n"
                f"Frequency bin : {frequency_bin}\n"
                f"STFT bins     : {stft.shape[0]}"
            )

        if (
            time_frame < 0
            or time_frame >= stft.shape[1]
        ):

            raise IndexError(
                "\nTime frame outside STFT bounds.\n"
                f"Bit index  : {bit_index}\n"
                f"Time frame : {time_frame}\n"
                f"STFT frames: {stft.shape[1]}"
            )

        # ----------------------------------------------------
        # Read coefficient
        # ----------------------------------------------------

        coefficient = stft[
            frequency_bin,
            time_frame,
        ].item()

        # ----------------------------------------------------
        # QIM decoding
        # ----------------------------------------------------

        extracted_bit = decode_qim(
            coefficient,
            adaptive_delta,
        )

        extracted_bits.append(
            extracted_bit
        )

        # ----------------------------------------------------
        # Record extraction details
        # ----------------------------------------------------

        details.append(
            {
                "bit_index": bit_index,
                "expected_bit": expected_bit,
                "extracted_bit": extracted_bit,
                "correct": int(
                    extracted_bit
                    == expected_bit
                ),
                "region_id": region_id,
                "time_frame": time_frame,
                "frequency_bin": frequency_bin,
                "semantic_score": semantic_score,
                "adaptive_delta": adaptive_delta,
                "received_real": float(
                    np.real(coefficient)
                ),
                "received_imag": float(
                    np.imag(coefficient)
                ),
                "normalized_value": float(
                    np.real(coefficient)
                    / adaptive_delta
                ),
            }
        )

    return (
        extracted_bits,
        details,
    )


# ============================================================
# AUDIO -> STFT
# ============================================================

def reconstruct_stft_from_audio() -> tuple[
    torch.Tensor,
    int,
    int,
]:
    """
    Load the watermarked WAV generated by Experiment 17
    and reconstruct its STFT using exactly the same STFT
    configuration.

    Returns:

        reconstructed_stft
        sample_rate
        number_of_samples
    """

    check_file_exists(
        WATERMARKED_AUDIO_FILE,
        "QIM watermarked audio",
    )

    audio, sample_rate = librosa.load(
        WATERMARKED_AUDIO_FILE,
        sr=None,
        mono=True,
    )

    stft = librosa.stft(
        audio,
        n_fft=N_FFT,
        hop_length=HOP_LENGTH,
        win_length=WIN_LENGTH,
    )

    reconstructed_stft = (
        torch.from_numpy(
            stft
        )
    )

    return (
        reconstructed_stft,
        int(sample_rate),
        len(audio),
    )


# ============================================================
# EXTRACTION METRICS
# ============================================================

def calculate_bit_metrics(
    expected_bits: np.ndarray,
    extracted_bits: np.ndarray,
) -> dict:
    """
    Calculate watermark extraction accuracy.
    """

    if len(expected_bits) != len(
        extracted_bits
    ):

        raise ValueError(
            "\nExpected and extracted payload "
            "lengths do not match."
        )

    total_bits = len(
        expected_bits
    )

    correct_bits = int(
        np.sum(
            expected_bits
            == extracted_bits
        )
    )

    incorrect_bits = (
        total_bits
        - correct_bits
    )

    bit_accuracy = (
        correct_bits
        / total_bits
    )

    bit_error_rate = (
        incorrect_bits
        / total_bits
    )

    return {
        "total_bits": int(
            total_bits
        ),
        "correct_bits": int(
            correct_bits
        ),
        "incorrect_bits": int(
            incorrect_bits
        ),
        "bit_accuracy": float(
            bit_accuracy
        ),
        "bit_error_rate": float(
            bit_error_rate
        ),
    }


# ============================================================
# EXTRACTION DETAIL STATISTICS
# ============================================================

def calculate_sign_statistics(
    details: list[dict],
) -> dict:
    """
    Calculate statistics based on whether the received
    real coefficient is positive or negative.

    These are diagnostic statistics only.
    """

    positive = 0
    negative = 0
    zero = 0

    for row in details:

        value = float(
            row["received_real"]
        )

        if value > 0:
            positive += 1

        elif value < 0:
            negative += 1

        else:
            zero += 1

    return {
        "positive_real_coefficients": positive,
        "negative_real_coefficients": negative,
        "zero_real_coefficients": zero,
    }


# ============================================================
# SAVE RESULTS
# ============================================================

def save_results(
    name: str,
    extracted_bits: list[int],
    details: list[dict],
    metrics: dict,
    sign_statistics: dict,
) -> None:
    """
    Save extracted bits, detailed CSV, and summary JSON.
    """

    extracted_tensor = torch.tensor(
        extracted_bits,
        dtype=torch.int64,
    )

    torch.save(
        extracted_tensor,
        OUTPUT_DIR / f"{name}_bits.pt",
    )

    with open(
        OUTPUT_DIR / f"{name}_bits.txt",
        "w",
    ) as file:

        file.write(
            "".join(
                str(bit)
                for bit in extracted_bits
            )
        )

    details_df = pd.DataFrame(
        details
    )

    details_df.to_csv(
        OUTPUT_DIR / f"{name}_details.csv",
        index=False,
    )

    summary = {
        "extraction_method": name,
        **metrics,
        **sign_statistics,
    }

    with open(
        OUTPUT_DIR / f"{name}_summary.json",
        "w",
    ) as file:

        json.dump(
            summary,
            file,
            indent=4,
        )


