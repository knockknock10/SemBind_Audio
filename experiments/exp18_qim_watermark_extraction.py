"""
SemBind-Audio
Experiment 18

QIM Watermark Extraction & Verification

Purpose
-------
Validate the semantic-adaptive QIM watermark produced by Experiment 17.

Two extraction paths are evaluated:

1. Direct STFT extraction
   -----------------------
   Extract directly from:
       results/qim_embedding/qim_watermarked_stft.pt

   This validates the mathematical correctness of the QIM
   embedding/extraction pair without introducing audio
   reconstruction effects.

2. Audio round-trip extraction
   ----------------------------
   Extract from:
       QIM watermarked STFT
           -> watermarked WAV
           -> STFT reconstruction
           -> QIM extraction

   This evaluates whether the watermark survives the
   STFT -> audio -> STFT round trip.

Ground-truth payload:
    results/watermark/payload_bits.pt

QIM decoder:
    bit_hat = round(real(y) / Delta) mod 2

Important:
    Experiment 17 modifies only the REAL component of the
    selected complex STFT coefficients. Therefore extraction
    also operates on the REAL component.
"""

